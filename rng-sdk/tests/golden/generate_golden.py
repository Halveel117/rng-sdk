#!/usr/bin/env python3
"""Generate golden (known-answer) values for the C++ test suite from an
INDEPENDENT implementation stack: Python hashlib/hmac (OpenSSL-backed) for
all crypto, NumPy for PCG64, and a direct transcription of the canonical
xoshiro256++ reference C for the fast engine.

Rationale: embedding values produced by the C++ code itself would only prove
self-consistency. These values are produced by different codebases, so any
C++ porting bug (endianness, type widths, spec misreading) fails the tests.

Run:  python3 generate_golden.py   ->  prints a C++ header to stdout.
"""
import hashlib
import hmac as hmac_mod
import struct

MASK64 = (1 << 64) - 1


# ---------- SplitMix64 / xoshiro256++ (transcribed from prng.di.unimi.it) ----
def splitmix64_stream(seed):
    state = seed & MASK64
    while True:
        state = (state + 0x9E3779B97F4A7C15) & MASK64
        z = state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK64
        yield (z ^ (z >> 31)) & MASK64


def rotl(x, k):
    return ((x << k) | (x >> (64 - k))) & MASK64


class Xoshiro256pp:
    def __init__(self, s):
        self.s = list(s)

    @classmethod
    def from_seed(cls, seed):
        g = splitmix64_stream(seed)
        return cls([next(g) for _ in range(4)])

    def next(self):
        s = self.s
        result = (rotl((s[0] + s[3]) & MASK64, 23) + s[0]) & MASK64
        t = (s[1] << 17) & MASK64
        s[2] ^= s[0]
        s[3] ^= s[1]
        s[1] ^= s[2]
        s[0] ^= s[3]
        s[2] ^= t
        s[3] = rotl(s[3], 45)
        return result

    # jump()/long_jump() from the same reference C. These advance the state by
    # 2^128 / 2^192 steps, which is what makes per-thread streams provably
    # non-overlapping — a safety property the C++ side asserted in a comment
    # with no vector behind it until this was added (audit finding CA-05).
    JUMP = [0x180EC6D33CFD0ABA, 0xD5A61266F0C9392C,
            0xA9582618E03FC9AA, 0x39ABDC4529B1661C]
    LONG_JUMP = [0x76E15D3EFEFDCBBF, 0xC5004E441C522FB3,
                 0x77710069854EE241, 0x39109BB02ACBE635]

    def _do_jump(self, table):
        acc = [0, 0, 0, 0]
        for word in table:
            for b in range(64):
                if word & (1 << b):
                    for i in range(4):
                        acc[i] ^= self.s[i]
                self.next()
        self.s = acc

    def jump(self):
        self._do_jump(self.JUMP)

    def long_jump(self):
        self._do_jump(self.LONG_JUMP)


# ---------- PCG64 via NumPy (state injection) --------------------------------
def pcg64_numpy(initstate, initseq, n):
    """Replicate reference srandom seeding in Python, inject into NumPy."""
    from numpy.random import PCG64
    MASK128 = (1 << 128) - 1
    MULT = 0x2360ed051fc65da44385df649fccf645
    inc = ((initseq << 1) | 1) & MASK128
    state = 0
    state = (state * MULT + inc) & MASK128          # step
    state = (state + initstate) & MASK128
    state = (state * MULT + inc) & MASK128          # step
    bg = PCG64()
    st = bg.state
    st["state"] = {"state": state, "inc": inc}
    st["has_uint32"] = 0
    st["uinteger"] = 0
    bg.state = st
    return [int(x) for x in bg.random_raw(n)]


# ---------- HMAC-DRBG (SP 800-90A) independent Python implementation ---------
class HmacDrbg:
    def __init__(self, entropy, nonce=b"", personalization=b""):
        self.K = b"\x00" * 32
        self.V = b"\x01" * 32
        self._update(entropy + nonce + personalization)
        self.reseed_counter = 1

    def _hmac(self, key, msg):
        return hmac_mod.new(key, msg, hashlib.sha256).digest()

    def _update(self, provided):
        self.K = self._hmac(self.K, self.V + b"\x00" + provided)
        self.V = self._hmac(self.K, self.V)
        if provided:
            self.K = self._hmac(self.K, self.V + b"\x01" + provided)
            self.V = self._hmac(self.K, self.V)

    def generate(self, n, additional=b""):
        if additional:
            self._update(additional)
        out = b""
        while len(out) < n:
            self.V = self._hmac(self.K, self.V)
            out += self.V
        self._update(additional)
        self.reseed_counter += 1
        return out[:n]


def cpp_u64_list(name, vals):
    body = ", ".join(f"0x{v:016x}ULL" for v in vals)
    return f"inline constexpr std::uint64_t {name}[] = {{{body}}};"


def cpp_str(name, s):
    return f'inline const char* {name} = "{s}";'


def main():
    out = []
    out.append("// AUTO-GENERATED by tests/golden/generate_golden.py — do not edit.")
    out.append("// Values come from independent implementations (Python hashlib/hmac,")
    out.append("// NumPy PCG64, canonical xoshiro transcription). See that script.")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("namespace golden {")

    # SHA-256 (FIPS 180-4 style vectors, values via hashlib)
    out.append(cpp_str("kSha256Empty", hashlib.sha256(b"").hexdigest()))
    out.append(cpp_str("kSha256Abc", hashlib.sha256(b"abc").hexdigest()))
    two_block = b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"
    out.append(cpp_str("kSha256TwoBlock", hashlib.sha256(two_block).hexdigest()))
    out.append(cpp_str("kSha256MillionA", hashlib.sha256(b"a" * 1000000).hexdigest()))

    # HMAC-SHA256 (RFC 4231 cases 1, 2, 6 — short key, text key, oversize key)
    k1, d1 = b"\x0b" * 20, b"Hi There"
    out.append(cpp_str("kHmacCase1", hmac_mod.new(k1, d1, hashlib.sha256).hexdigest()))
    k2, d2 = b"Jefe", b"what do ya want for nothing?"
    out.append(cpp_str("kHmacCase2", hmac_mod.new(k2, d2, hashlib.sha256).hexdigest()))
    k6 = b"\xaa" * 131
    d6 = b"Test Using Larger Than Block-Size Key - Hash Key First"
    out.append(cpp_str("kHmacCase6", hmac_mod.new(k6, d6, hashlib.sha256).hexdigest()))

    # HMAC-DRBG: entropy = bytes 0..31, no nonce/personalization.
    drbg = HmacDrbg(bytes(range(32)))
    g1 = drbg.generate(64)
    g2 = drbg.generate(64)   # second call continues the chain
    out.append(cpp_str("kDrbgGen1", g1.hex()))
    out.append(cpp_str("kDrbgGen2", g2.hex()))
    # With personalization + additional input on generate.
    drbg2 = HmacDrbg(bytes(range(32)), b"", b"rngsdk-test-personalization")
    g3 = drbg2.generate(32, b"additional-input")
    out.append(cpp_str("kDrbgPersAdd", g3.hex()))

    # DRBG engine convenience seeding: seed 42 -> sha256("rngsdk-drbg-seed" + LE64(42))
    material = b"rngsdk-drbg-seed" + struct.pack("<Q", 42)
    seed_bytes = hashlib.sha256(material).digest()
    eng = HmacDrbg(seed_bytes)
    buf = eng.generate(4096)
    engine_words = [struct.unpack_from("<Q", buf, 8 * i)[0] for i in range(4)]
    out.append(cpp_u64_list("kDrbgEngineSeed42", engine_words))

    # xoshiro256++: raw state [1,2,3,4] and seed 42 via SplitMix64.
    x = Xoshiro256pp([1, 2, 3, 4])
    out.append(cpp_u64_list("kXoshiroState1234", [x.next() for _ in range(6)]))
    x42 = Xoshiro256pp.from_seed(42)
    out.append(cpp_u64_list("kXoshiroSeed42", [x42.next() for _ in range(6)]))

    # Jump / LongJump from seed 7. Without these the C++ DoJump port was
    # unvalidated, while the header claimed jumped streams are guaranteed
    # non-overlapping — the property multithreaded users rely on.
    xj = Xoshiro256pp.from_seed(7)
    xj.jump()
    out.append(cpp_u64_list("kXoshiroSeed7Jump", [xj.next() for _ in range(6)]))
    xlj = Xoshiro256pp.from_seed(7)
    xlj.long_jump()
    out.append(cpp_u64_list("kXoshiroSeed7LongJump", [xlj.next() for _ in range(6)]))

    # PCG64: initstate = 42, initseq = 54 (the pcg-random demo pair), and a
    # 128-bit pair exercising the high limbs.
    out.append(cpp_u64_list("kPcg64Demo", pcg64_numpy(42, 54, 6)))
    hi_state = (0x0123456789abcdef << 64) | 0xfedcba9876543210
    hi_seq = (0x0f0e0d0c0b0a0908 << 64) | 0x0706050403020100
    out.append(cpp_u64_list("kPcg64Wide", pcg64_numpy(hi_state, hi_seq, 6)))

    # Provably Fair: server "s3cret-server-seed", client "player-seed", nonce 7.
    server, client, nonce = b"s3cret-server-seed", "player-seed", 7
    out.append(cpp_str("kPfCommitment", hashlib.sha256(server).hexdigest()))

    def pf_block(cursor):
        msg = f"{client}:{nonce}:{cursor}".encode()
        return hmac_mod.new(server, msg, hashlib.sha256).digest()

    stream = pf_block(0) + pf_block(1)
    floats = []
    for i in range(12):   # 12 floats = 48 bytes -> crosses the cursor boundary
        b = stream[4 * i:4 * i + 4]
        floats.append(b[0] / 2**8 + b[1] / 2**16 + b[2] / 2**24 + b[3] / 2**32)
    body = ", ".join(repr(f) for f in floats)
    out.append(f"inline constexpr double kPfFloats[] = {{{body}}};")

    out.append("} // namespace golden")
    print("\n".join(out))


if __name__ == "__main__":
    main()
